    #[tokio::test]
    async fn operation_possession_and_request_hash_are_required_before_consuming_slot() {
        let f = Fixture::new().await;
        assert_eq!(
            f.sessions
                .begin_authenticated(
                    &f.grant_wire,
                    &f.keywrap,
                    &f.recorder_public,
                    &"00".repeat(64)
                )
                .err(),
            Some(SessionError::InvalidPossession)
        );
        let (session, evidence) = f.capture_software().await;
        assert_eq!(
            f.resource
                .challenge(session.session_id(), &f.recorder_public, &"00".repeat(64))
                .err(),
            Some(ResourceError::InvalidPossession)
        );
        let resource = f.resource_challenge(&session, &evidence);
        let request = f.request(&resource);
        let signature = f.decision_signature(&resource, &request);
        let mut other = request.clone();
        other.resource_path[0] = "other-tenant".into();
        assert_eq!(
            f.resource
                .decide(session.session_id(), &other, &f.recorder_public, &signature)
                .await
                .err(),
            Some(ResourceError::InvalidPossession)
        );
        let attacker = key();
        let attacker_public: [u8; 32] = attacker.public_key().as_ref().try_into().unwrap();
        assert_eq!(
            f.resource
                .decide(session.session_id(), &request, &attacker_public, &signature)
                .await
                .err(),
            Some(ResourceError::InvalidPossession)
        );
        assert!(matches!(
            f.resource
                .decide(
                    session.session_id(),
                    &request,
                    &f.recorder_public,
                    &signature
                )
                .await
                .unwrap(),
            ResourceOutcome::Current(_)
        ));
        let other_signature = f.decision_signature(&resource, &other);
        assert_eq!(
            f.resource
                .decide(
                    session.session_id(),
                    &other,
                    &f.recorder_public,
                    &other_signature
                )
                .await
                .err(),
            Some(ResourceError::Conflict)
        );
    }

