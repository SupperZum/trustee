    #[tokio::test]
    async fn actual_aggregate_to_durable_issuer_to_guest_is_one_time_and_preparation_stays_closed()
    {
        let scenario = scenario().await;
        let first = scenario
            .issuer
            .redeem_policy_aggregate(
                scenario.grant.grant_id(),
                &scenario.aggregate_wire,
                &scenario.redeem_request,
            )
            .unwrap();
        assert!(first.publication == AdmissionPublicationKind::FirstAuthorized);
        let retry = scenario
            .issuer
            .redeem_policy_aggregate(
                scenario.grant.grant_id(),
                &scenario.aggregate_wire,
                &scenario.redeem_request,
            )
            .unwrap();
        assert!(retry.publication == AdmissionPublicationKind::Existing);
        assert_eq!(
            first.signed_authorization_json,
            retry.signed_authorization_json
        );
        assert_eq!(
            scenario.gate.verify_bundle(
                &scenario.grant_wire,
                &scenario.aggregate_wire,
                &first.signed_authorization_json
            ),
            Ok(AdmissionCheck::FirstVerified)
        );
        assert_eq!(
            scenario.gate.verify_bundle(
                &scenario.grant_wire,
                &scenario.aggregate_wire,
                &first.signed_authorization_json
            ),
            Ok(AdmissionCheck::Historical)
        );
        assert_eq!(scenario.gate.status(), Ok(GateStatus::Verified));
        assert!(matches!(
            scenario.gate.validate_for_preparation(
                &scenario.grant_wire,
                &scenario.aggregate_wire,
                &first.signed_authorization_json
            ),
            Err(GuestAdmissionError::Unsupported(
                GuestUnsupportedReason::ContentPreparationUnavailable
            ))
        ));
    }

